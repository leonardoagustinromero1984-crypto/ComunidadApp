    fun isCanonicalStagingUrl(url: String?): Boolean {
        if (url.isNullOrBlank()) return false
        if (url.contains(STAGING_PROJECT_REF, ignoreCase = true)) return true
        return LeoVerAuthDomains.isOfficialStagingAuthHost(url)
    }

    fun isLegacyProjectUrl(url: String?): Boolean =
        !url.isNullOrBlank() && url.contains(LEGACY_PROJECT_REF, ignoreCase = true)
}
